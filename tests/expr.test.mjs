import * as E from "../src/math/expr";
import * as C from "../src/math/complex";
let failed = 0;
const ok = (n, c, x = "") => { if (!c) { failed++; console.log("FAIL", n, x); } else console.log("ok  ", n); };
const near = (a, b, t = 1e-9) => Math.abs(a - b) < t;
const R = (s, ...a) => { const r = E.compileReal(s, ["x", "y"]); if (!r.ok) throw new Error(s + ": " + r.error); return r.f(...a); };
ok("precedence", R("2+3*4", 0, 0) === 14);
ok("power right-assoc", R("2^3^2", 0, 0) === 512);
ok("unary minus below ^", R("-x^2", 3, 0) === -9);
ok("2^-1", near(R("2^-1", 0, 0), 0.5));
ok("implicit mult 2x", R("2x", 3, 0) === 6);
ok("implicit mult 3(x+1)", R("3(x+1)", 1, 0) === 6);
ok("x y implicit", R("x y", 2, 5) === 10);
ok("2 pi", near(R("2pi", 0, 0), 2 * Math.PI));
ok("π and ²", near(R("π x²", 2, 0), 4 * Math.PI));
ok("functions", near(R("sin(x)*cos(y)+exp(0)", Math.PI / 2, 0), 2));
ok("two-arg", R("max(x, y) + atan2(0, 1)", 2, 7) === 7);
ok("sci notation", R("1e-3*x", 1000, 0) === 1);
ok("** power", R("x**2", 4, 0) === 16);
ok("nested parens", R("((x+1)*(y-1))/2", 3, 5) === 8);
for (const [src, msg] of [["x +", "ends"], ["(x", "parenthesis"], ["sin x", "parentheses"], ["foo(x)", "Unknown"], ["x $ y", "Unexpected"], ["", "Type"], ["sin()", "argument"], ["x y q", "Unknown"], ["atan2(1)", "2 argument"], ["x)", "Unexpected"]]) {
  const r = E.compileReal(src, ["x", "y"]);
  ok(`error "${src}"`, !r.ok && r.error.includes(msg), JSON.stringify(r));
}
const Cx = (s, z) => { const r = E.compileComplex(s); if (!r.ok) throw new Error(s + ": " + r.error); return r.f(z); };
const nearC = (a, b, t = 1e-9) => near(a[0], b[0], t) && near(a[1], b[1], t);
ok("z^2", nearC(Cx("z^2", [1, 2]), [-3, 4]));
ok("1/z", nearC(Cx("1/z", [0, 1]), [0, -1]));
ok("i*i", nearC(Cx("i*i", [0, 0]), [-1, 0]));
ok("e^(i pi)", nearC(Cx("e^(i*pi)", [0, 0]), [-1, 0], 1e-12));
ok("exp(i pi)+1", nearC(Cx("exp(i*pi)+1", [0, 0]), [0, 0], 1e-12));
ok("implicit 2iz", nearC(Cx("2i z", [1, 1]), [-2, 2]));
ok("z^0.5 = sqrt z", nearC(Cx("z^0.5", [-4, 0]), Cx("sqrt(z)", [-4, 0]), 1e-9));
ok("sqrt(-4) = 2i", nearC(Cx("sqrt(z)", [-4, 0]), [0, 2]));
ok("z^z at i", (() => { const r = Cx("z^z", [0, 1]); return near(r[0], Math.exp(-Math.PI / 2), 1e-9) && near(r[1], 0, 1e-9); })());
ok("sin(z) matches lib", nearC(Cx("sin(z)", [0.7, -1.3]), C.sin([0.7, -1.3])));
ok("tan = sin/cos", nearC(Cx("tan(z)", [0.4, 0.3]), C.div(C.sin([0.4, 0.3]), C.cos([0.4, 0.3]))));
ok("sinh^2 - cosh^2 = -1", nearC(Cx("sinh(z)^2 - cosh(z)^2", [0.3, 1.1]), [-1, 0], 1e-9));
ok("conj/abs/re/im", nearC(Cx("conj(z) + abs(z) + re(z) + 2 im(z)", [3, 4]), [19, -4]));
ok("x,y as parts", nearC(Cx("x + i y", [2, 5]), [2, 5]));
ok("pow(z,3)", nearC(Cx("pow(z,3)", [1, 1]), C.powInt([1, 1], 3)));
ok("complex unknown", !E.compileComplex("q + 1").ok && E.compileComplex("q + 1").error.includes("Unknown"));
ok("derivative of z^3", (() => { const f = E.compileComplex("z^3").f; return nearC(E.complexDerivative(f, [0.5, 0.8]), C.scale(C.powInt([0.5, 0.8], 2), 3), 1e-6); })());
ok("numeric gradient", (() => { const f = E.compileReal("x^2*y + sin(y)", ["x", "y"]).f; const g = E.numericGradient(f, 1.2, 0.7); return near(g[0], 2 * 1.2 * 0.7, 1e-7) && near(g[1], 1.44 + Math.cos(0.7), 1e-7); })());
ok("0^-1 gives non-finite not crash", !Number.isFinite(Cx("z^-1", [0, 0])[0]));
console.log(failed ? `\n${failed} FAILED` : "\nall passed");
